// 받침에 따라 조사를 고른다: josa('강태풍', '이', '가') → '이'
function josa(word, withBatchim, without) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  return code >= 0 && code <= 11171 && code % 28 ? withBatchim : without;
}

