async function shareResult(no) {
  const r = loadRecords().find(x => x.no === no) || UI.rec; if (!r) return;
  const text = shareText(r);
  try {
    const url = await cardDataUrl(r), blob = await (await fetch(url)).blob();
    const file = new File([blob], `yangil-${recNo(r.no)}.png`, { type: 'image/png' });
    if (navigator.canShare && navigator.canShare({ files: [file] })) { await navigator.share({ files: [file], text }); return; }
    if (navigator.share) { await navigator.share({ text }); return; }
  } catch (e) { if (e && e.name === 'AbortError') return; }
  try { await navigator.clipboard.writeText(text); toast('결과 문구를 복사했어! 카톡에 붙여 넣고, 카드는 「PNG로 저장」해서 같이 보내 줘.'); }
  catch (e) { UI.shareText = text; toast('아래 문구를 길게 눌러 복사해 줘.'); render(); }
}

/* ───────── 배경음악 ─────────
   설치 없이 브라우저에서 바로 만드는 잔잔한 8마디 루프 (C-Am-F-G). 처음 화면을 누른 뒤부터 나온다. */
const BGM = {
  on: store.get('yangil.bgm', true), ctx: null, timer: null, step: 0, next: 0, gain: null,
  // 16분음표 단위 멜로디 (0 = 쉼표). 8마디 × 8칸
  melody: [72, 0, 76, 0, 79, 0, 76, 0, 77, 0, 76, 74, 72, 0, 0, 0, 69, 0, 72, 0, 76, 0, 74, 0, 72, 0, 71, 0, 69, 0, 0, 0,
           65, 0, 69, 0, 72, 0, 74, 0, 72, 0, 69, 0, 65, 0, 67, 0, 67, 0, 71, 0, 74, 0, 72, 0, 71, 0, 69, 0, 67, 0, 0, 0],
  bass: [48, 45, 41, 43], // 마디 2개씩: C · Am · F · G
  hz: n => 440 * Math.pow(2, (n - 69) / 12),
  note(f, t, dur, type, vol) {
    const c = this.ctx, o = c.createOscillator(), g = c.createGain();
    o.type = type; o.frequency.setValueAtTime(f, t);
    g.gain.setValueAtTime(0.0001, t); g.gain.exponentialRampToValueAtTime(vol, t + 0.02); g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
    o.connect(g).connect(this.gain); o.start(t); o.stop(t + dur + 0.05);
  },
  tick() {
    const c = this.ctx, len = 0.27; // 한 칸 길이(초)
    while (this.next < c.currentTime + 0.4) {
      const i = this.step % this.melody.length, m = this.melody[i];
      if (m) this.note(this.hz(m), this.next, len * 1.8, 'triangle', 0.05);
      if (i % 8 === 0) { const b = this.bass[Math.floor(i / 16) % 4]; this.note(this.hz(b), this.next, len * 7.5, 'sine', 0.06); this.note(this.hz(b + 7), this.next + len * 4, len * 3.5, 'sine', 0.035); }
      this.next += len; this.step++;
    }
  },
  start() {
    if (!this.on || this.timer) return;
    try {
      this.ctx = this.ctx || new (window.AudioContext || window.webkitAudioContext)();
      if (this.ctx.state === 'suspended') this.ctx.resume();
      if (!this.gain) { this.gain = this.ctx.createGain(); this.gain.gain.value = 0.7; this.gain.connect(this.ctx.destination); }
      this.next = this.ctx.currentTime + 0.1;
      this.timer = setInterval(() => this.tick(), 120);
    } catch (e) { /* 소리를 낼 수 없는 환경 */ }
  },
  stop() { clearInterval(this.timer); this.timer = null; },
  toggle() { this.on = !this.on; store.set('yangil.bgm', this.on); if (this.on) this.start(); else this.stop(); },
};
// 브라우저는 사용자가 화면을 한 번 눌러야 소리를 허락한다
document.addEventListener('pointerdown', () => BGM.start(), { once: true });
document.addEventListener('keydown', () => BGM.start(), { once: true });
document.addEventListener('visibilitychange', () => { if (document.hidden) BGM.stop(); else if (BGM.ctx) BGM.start(); });
