const ROSTER_SIZE = { real: 12, classic: 4 };
function pickRoster(mode = 'real') {
  return CAMEO_IDS.filter(id => !CAMEOS[id].fixed).sort(() => Math.random() - 0.5).slice(0, ROSTER_SIZE[mode] || 8);
}
// 예전 저장 파일처럼 roster가 없으면 모두 나온다
function inRoster(s, id) {
  const c = CAMEOS[id];
  if (c.fixed) return s.mode === 'classic';
  return !s.roster || s.roster.includes(id) || !!(c.club && s.autoClub === c.club);
}
function rosterIds(s) { return CAMEO_IDS.filter(id => inRoster(s, id)); }

