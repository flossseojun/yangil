// 정답 근처의 그럴듯한 오답 (정답이 양수면 오답도 양수)
function numOpts(ans, spread, fmt = String) {
  const s = new Set([ans]); let guard = 0;
  while (s.size < 4 && guard++ < 50) { const v = ans + ri(-spread, spread); if (v !== ans && (ans <= 0 || v > 0)) s.add(v); }
  for (let k = 1; s.size < 4; k++) s.add(ans + k * (spread + 1));
  return [...s].map(fmt);
}
