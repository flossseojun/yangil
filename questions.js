function makeQuestion(area, year, name) {
  const topic = topicOf(name, area);
  if (topic === 'khist' && Math.random() < 0.25) { const [x, y] = TIMELINE.slice().sort(() => Math.random() - 0.5); return { area, sub: name, q: '둘 중 먼저 일어난 일은?', a: x[1] < y[1] ? x[0] : y[0], opts: [x[0], y[0]] }; }
  const raw = quizItem(topic, area, year);
  if (raw[0] === 'ox') return { area, sub: name, q: `O / X : ${raw[1]}`, a: raw[2] ? 'O' : 'X', opts: ['O', 'X'] };
  const [q, a, ...wrong] = raw;
  return { area, sub: name, q, a, opts: [a, ...wrong].sort(() => Math.random() - 0.5) };
}
