const semKey = s => `${s.year}-${s.sem}`;
// 이번 학기 선택군. 2학년부터는 계열에 맞는 과목과 공통 과목만 보이고, 3학년 2학기는 1학기에 들은 과목을 뺀다.
function courseGroups(key, track, taken = []) {
  const n = SCHOOL.grades[+key[0]].total;
  return CURRICULUM[key].groups.map(g => {
    const list = g.list.filter(x => (!x.tag || !track || x.tag === track) && !taken.includes(x.name));
    const popSum = g.list.reduce((a, x) => a + (x.pop || 1), 0);
    return Object.assign({}, g, { list: list.map(x => Object.assign({ credits: g.credits, size: Math.max(12, Math.round(n * g.pick * (x.pop || 1) / popSum)) }, x)) });
  });
}
function takenBefore(s) { return s.year === 3 && s.sem === 2 ? (s.electives['3-1'] || []) : []; }

// 이번 학기에 등급이 나오는 과목들 (공통 + 선택, 예술은 성취평가라 제외)
function subjectsOf(s) {
  const key = semKey(s), n = SCHOOL.grades[s.year].total;
  const core = CURRICULUM[key].core.map(([name, area, credits]) => ({ name, key: area, area, size: n, credits }));
  const all = courseGroups(key, s.track, takenBefore(s)).flatMap(g => g.list);
  const picked = (s.electives[key] || []).map(name => all.find(x => x.name === name)).filter(x => x && x.graded !== false);
  return core.concat(picked.map(x => Object.assign({ key: x.name }, x)));
}

